#!/usr/bin/env python3
"""Emit a REALISTIC Wyn program of a requested size, for compile-time scaling.

Why a generator and not two checked-in files: the published compile-time rows
are quoted at specific sizes (1,063 and 5,065 lines), and the correction that
produced those rows was that the FIXTURE, not the machine, decided the answer.
5,000 lines of one repeated statement type-check in ~19ms; 5,000 lines of
realistic code take ~72ms - 3.8x, same line count. So the fixture's SHAPE is the
measurement's most important input, and a generator states that shape in one
place instead of burying it in two large files nobody reads.

Shape, per generated unit (~40 lines): a struct with an `impl` block (static
constructor + two methods), an enum with payload arms, a `match` over it, an
`Option`-returning linear lookup, a generic function, and a driver function that
calls all of the above. Every symbol carries the unit index, so nothing is
shared: the checker has to resolve N distinct types, not re-walk one.

`wyn check` scales with the number of DECLARATIONS, mildly superlinearly - not
with line count. Quote the unit count next to any number taken from this.

Usage:
    gen_scale_fixture.py --lines 1063 -o scale_1063.wyn
    gen_scale_fixture.py --units 26   -o scale_26u.wyn
Prints one line of JSON describing what it actually wrote.
"""
import argparse
import json
import sys

# Every `{i}` becomes the unit index, so no two units share a symbol.
UNIT = '''
// ---- unit {i} ---------------------------------------------------------------
struct Rec{i} {{
    id: int,
    label: string,
    score: float
}}

impl Rec{i} {{
    fn new(id: int, label: string) -> Rec{i} {{
        return Rec{i} {{ id: id, label: label, score: 0.0 }}
    }}
    fn describe(self) -> string {{
        return "Rec{i}#${{self.id}}/${{self.label}}"
    }}
    fn bump(self, by: int) -> int {{
        return self.id + by * {k}
    }}
}}

enum Ev{i} {{ Hit{i}(int), Miss{i}(string), Idle{i} }}

fn score_ev{i}(e: Ev{i}) -> int {{
    return match e {{
        Ev{i}.Hit{i}(n) => n * 2
        Ev{i}.Miss{i}(s) => s.len()
        Ev{i}.Idle{i} => 0
    }}
}}

fn find{i}(xs: [int], want: int) -> int? {{
    for x in xs {{
        if x == want {{ return Some(x) }}
    }}
    return None
}}

fn pick{i}<T>(a: T, b: T, first: int) -> T {{
    if first == 1 {{ return a }}
    return b
}}

fn unit{i}(seed: int) -> int {{
    var r = Rec{i}.new(seed, "u{i}")
    var acc = r.bump(3)
    var xs: [int] = []
    for j in 0..8 {{ xs.push(seed + j * {k}) }}
    var hit = find{i}(xs, seed + 3 * {k})
    acc = acc + match hit {{
        Some(v) => v
        none => 0
    }}
    acc = acc + score_ev{i}(Ev{i}.Hit{i}(seed))
    acc = acc + score_ev{i}(Ev{i}.Miss{i}(r.describe()))
    acc = acc + score_ev{i}(Ev{i}.Idle{i})
    acc = acc + pick{i}(1, 2, seed % 2)
    return acc
}}
'''

HEADER = '''// GENERATED by benchmarks/harness/gen_scale_fixture.py - do not hand-edit.
// {units} units, {decls} top-level declarations. Realistic code: every unit has
// its own struct + impl, enum with payloads, match, Option-returning lookup and
// generic fn, with distinct symbol names throughout. Regenerate, do not patch.
'''

MAIN_HEAD = '''
fn main() -> int {
    var total = 0
'''
MAIN_CALL = '    total = total + unit{i}({i} + 1)\n'
MAIN_TAIL = '''    print("scale fixture total=${total}")
    return 0
}
'''

# Declarations per unit: struct, impl, enum, score_ev, find, pick, unit.
DECLS_PER_UNIT = 7


def render(units):
    body = "".join(UNIT.format(i=i, k=(i % 7) + 1) for i in range(units))
    main = MAIN_HEAD + "".join(MAIN_CALL.format(i=i) for i in range(units)) + MAIN_TAIL
    head = HEADER.format(units=units, decls=units * DECLS_PER_UNIT + 1)
    return head + body + main


def units_for_lines(target):
    """Smallest unit count whose render is >= target lines, then step back if the
    previous count lands closer. The generator cannot hit an arbitrary line count
    exactly - a unit is atomic - so report what was actually written."""
    n = 1
    while len(render(n).splitlines()) < target:
        n += 1
    if n > 1:
        lo = abs(len(render(n - 1).splitlines()) - target)
        hi = abs(len(render(n).splitlines()) - target)
        if lo < hi:
            n -= 1
    return n


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--lines", type=int, help="approximate target line count")
    g.add_argument("--units", type=int, help="exact unit count")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    units = a.units if a.units else units_for_lines(a.lines)
    text = render(units)
    with open(a.out, "w") as f:
        f.write(text)
    print(json.dumps({
        "out": a.out,
        "units": units,
        "lines": len(text.splitlines()),
        "declarations": units * DECLS_PER_UNIT + 1,
        "requested_lines": a.lines,
    }))
    return 0


if __name__ == "__main__":
    sys.exit(main())
